# Фразы ожидания (когда агент думает, не вызывая инструмент)
THINKING_PHRASES: list[str] = [
    "Думаю…",
    "Обрабатываю запрос…",
    "Формирую ответ…",
    "Анализирую…",
]

# Фраза по умолчанию — если инструмент не в словаре
DEFAULT_PHRASES: list[str] = [
    "Выполняю задачу…",
    "Обрабатываю…",
    "Работаю над запросом…",
]


def get_tool_status(tool_name: str) -> str:
    """Вернуть случайную фразу для инструмента."""
    phrases = TOOL_STATUS_PHRASES.get(tool_name, DEFAULT_PHRASES)
    return random.choice(phrases)


def get_thinking_status() -> str:
    """Вернуть случайную фразу 'думаю'."""
    return random.choice(THINKING_PHRASES)


def get_tools_status(tool_names: list[str]) -> str:
    """
    Для нескольких инструментов — случайная фраза от первого.
    Если инструментов больше одного — добавляем счётчик.
    """
    if not tool_names:
        return random.choice(DEFAULT_PHRASES)

    phrase = get_tool_status(tool_names[0])

    if len(tool_names) > 1:
        # Убираем многоточие, дописываем счётчик
        base = phrase.rstrip("…")
        phrase = f"{base} ({len(tool_names)} операции)…"

    return phrase
